"""The `[ui.sidebar.agents]` managed block: generate, install, undo.

Writing into the user's own config.toml is the riskiest thing this plugin
does, so every write is validated on a copy first and rolled back on failure.
"""

import os
import pathlib
import shutil
import tempfile

from . import herdrctl

BEGIN = "# >>> herdr-usage managed block"
END = "# <<< herdr-usage managed block"

# Catppuccin Mocha. Herdr strips ANSI from token values, so colour can only
# come from these per-token-name fg rules in the user's config.
COLOURS = {
    "ok": ("#a6e3a1", ""),
    "warn": ("#f9e2af", ""),
    "crit": ("#f38ba8", ", bold = true"),
    "none": ("#6c7086", ", dim = true"),
}

_EXTRAS = (
    ("show_model", "uq_model"),
    ("show_plan", "uq_plan"),
    ("show_burn", "uq_burn"),
    ("show_credits", "uq_extra"),
    ("show_cost", "uq_extra"),
    ("show_resets_in", "uq_burn"),
)


def _slug(key: str) -> str:
    from .render import _slug as slug

    return slug(key)


def generate(cfg: dict) -> str:
    display = cfg.get("display") or {}
    rows = []

    # `machine` renders only when the client has >1 machine connected, and
    # drops itself otherwise -- so it costs nothing on a single-machine setup
    # and prevents two machines' gauges from being indistinguishable.
    head = ['"state_icon"', '"machine"', '"agent"']
    if display.get("show_model"):
        head.append('"$uq_model"')
    if display.get("show_plan"):
        head.append('"$uq_plan"')
    rows.append("  [" + ", ".join(head) + "],")

    for key in display.get("gauges") or []:
        base = f"uq_g{_slug(key)}"
        variants = []
        for band, (fg, extra) in COLOURS.items():
            variants.append(
                f'    {{ token = "${base}_{band}", fg = "{fg}"{extra} }},'
            )
        rows.append("  [\n" + "\n".join(variants) + "\n  ],")

    extra_tokens = []
    for flag, token in _EXTRAS:
        if flag in ("show_model", "show_plan"):
            continue
        if display.get(flag) and f'"${token}"' not in extra_tokens:
            extra_tokens.append(f'"${token}"')
    if extra_tokens:
        rows.append("  [" + ", ".join(extra_tokens) + "],")

    rows.append('  ["workspace", "tab"],')

    return (
        "# Generated by herdr-usage. Edit via the settings popup, or run\n"
        "# `herdr plugin action invoke herdr-usage.setup-sidebar --undo` to remove.\n"
        "[ui.sidebar.agents]\n"
        "row_gap = 0\n"
        "rows = [\n" + "\n".join(rows) + "\n]\n"
    )


def _strip(text: str) -> str:
    """Remove the managed block and the blank line we added before it."""
    start = text.find(BEGIN)
    if start < 0:
        return text
    stop = text.find(END, start)
    if stop < 0:
        return text
    stop += len(END)
    if stop < len(text) and text[stop] == "\n":
        stop += 1
    head = text[:start]
    if head.endswith("\n\n"):
        head = head[:-1]
    return head + text[stop:]


def _wrap(block: str) -> str:
    """Markers belong to install, not to the block's author."""
    body = block if block.endswith("\n") else block + "\n"
    if body.startswith(BEGIN):
        return body
    return f"{BEGIN}\n{body}{END}\n"


def install(config_path, block: str, check=None) -> bool:
    """Replace or append the block, but only if the result still validates.

    On any validation failure the original file is restored byte-identically
    and False is returned -- the user's config is never left broken.
    """
    check = herdrctl.config_check if check is None else check
    path = pathlib.Path(config_path)
    original = path.read_bytes() if path.exists() else None
    text = original.decode("utf-8") if original is not None else ""

    body = _strip(text)
    if body and not body.endswith("\n"):
        body += "\n"
    candidate = body + ("\n" if body else "") + _wrap(block)

    if candidate.encode("utf-8") == original:
        return True

    fd, tmp = tempfile.mkstemp(
        dir=str(path.parent), prefix=".herdr-usage-", suffix=".toml"
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(candidate)
        if not check(tmp):
            return False
        path.write_text(candidate, encoding="utf-8")
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass

    if original is not None and not path.read_bytes():
        path.write_bytes(original)
        return False
    return True


def state_dir() -> pathlib.Path:
    env = os.environ.get("HERDR_PLUGIN_STATE_DIR")
    if env:
        return pathlib.Path(env)
    base = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    return pathlib.Path(base) / "herdr" / "plugins" / "herdr-usage"


def marker_path() -> pathlib.Path:
    return state_dir() / "uninstalled"


def undo(config_path) -> bool:
    """Remove the block and remember that removal was deliberate."""
    path = pathlib.Path(config_path)
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    had = BEGIN in text

    marker = marker_path()
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text("removed by setup-sidebar --undo\n", encoding="utf-8")

    if not had:
        return False
    path.write_text(_strip(text), encoding="utf-8")
    return True


def is_uninstalled() -> bool:
    return marker_path().exists()


def clear_marker() -> None:
    try:
        marker_path().unlink()
    except OSError:
        pass
